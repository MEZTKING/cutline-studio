import { chromium } from 'playwright-core';
import fs from 'node:fs';
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || chromium.executablePath(), args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 860 }, acceptDownloads: true });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(process.env.APP_URL || 'http://127.0.0.1:5173/', { waitUntil: 'networkidle' });
await page.waitForSelector('.app');
const png = await page.evaluate(async () => {
  const c = document.createElement('canvas'); c.width = 1280; c.height = 720; const x = c.getContext('2d');
  x.fillStyle = '#03130f'; x.fillRect(0, 0, 1280, 720);
  x.fillStyle = '#0f3b33'; x.fillRect(80, 80, 1120, 560);
  const blob = await new Promise((r) => c.toBlob((b) => r(b), 'image/png'));
  const bytes = new Uint8Array(await blob.arrayBuffer()); let s = '';
  for (let i = 0; i < bytes.length; i += 0x8000) s += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  return btoa(s);
});
await page.setInputFiles('input[type=file]', [{ name: 'plain.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') }]);
await page.waitForFunction(() => document.querySelectorAll('.clip').length >= 1, null, { timeout: 30000 });
await page.evaluate(() => {
  const s = window.__cutline.getState();
  s.updateClip(s.selection.clipId, { duration: 4, transform: { ...s.project.tracks.flatMap(t => t.clips)[0].transform, scale: 1 } });
  s.addCaptions([{ start: 0.2, end: 3.8, text: 'EXPORTED CAPTION PROOF' }]);
  s.setPlayhead(1);
});
await page.waitForTimeout(1200);
await page.locator('.topbar .btn.primary').click();
await page.waitForSelector('.modal');
await page.waitForTimeout(500);
await page.locator('.modal select').first().selectOption('1280x720');
const dlPromise = page.waitForEvent('download', { timeout: 180000 });
await page.locator('.modal-foot .btn.primary').click();
const dl = await dlPromise;
const file = 'test-results/caption-export.webm';
await dl.saveAs(file);
await page.waitForTimeout(500);

const verify = await browser.newPage();
await verify.goto(process.env.APP_URL || 'http://127.0.0.1:5173/', { waitUntil: 'domcontentloaded' });
const b64 = fs.readFileSync(file).toString('base64');
const out = await verify.evaluate(async (data) => {
  const bin = atob(data); const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  const blob = new Blob([bytes], { type: 'video/webm' });
  const v = document.createElement('video');
  v.src = URL.createObjectURL(blob); v.muted = true;
  await new Promise((res, rej) => { v.onloadedmetadata = res; v.onerror = () => rej(new Error('decode failed')); setTimeout(() => rej(new Error('timeout')), 15000); });
  v.currentTime = 1.0;
  await new Promise((res) => { v.onseeked = res; setTimeout(res, 4000); });
  const c = document.createElement('canvas'); c.width = v.videoWidth; c.height = v.videoHeight;
  const ctx = c.getContext('2d'); ctx.drawImage(v, 0, 0);
  const d = ctx.getImageData(0, Math.floor(c.height * 0.6), c.width, Math.floor(c.height * 0.4)).data;
  let bright = 0;
  for (let i = 0; i < d.length; i += 4) if (d[i] > 200 && d[i + 1] > 200 && d[i + 2] > 200) bright++;
  return { duration: v.duration, w: v.videoWidth, h: v.videoHeight, bright };
}, b64);
console.log(JSON.stringify({ ...out, sizeMB: (fs.statSync(file).size / 1e6).toFixed(2), errors }));
await browser.close();
process.exit(out.bright > 500 && errors.length === 0 ? 0 : 1);
