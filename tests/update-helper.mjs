import { createRequire } from 'node:module';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
const require = createRequire(import.meta.url);
const { UNIX_HELPER } = require('../desktop/updater.cjs');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'cutline-helper-'));
const app = path.join(tmp, 'app');
const stage = path.join(tmp, 'stage');
const marker = path.join(tmp, 'launched.txt');
fs.mkdirSync(app);
fs.mkdirSync(stage);
fs.writeFileSync(path.join(app, 'old.txt'), 'old');
fs.writeFileSync(path.join(app, 'run.sh'), '#!/bin/sh\necho old > "' + path.join(tmp, 'old-launched.txt') + '"\n');
fs.writeFileSync(path.join(stage, 'new.txt'), 'new');
fs.writeFileSync(path.join(stage, 'run.sh'), '#!/bin/sh\necho new > "' + marker + '"\n');
const script = path.join(tmp, 'apply.sh');
fs.writeFileSync(script, UNIX_HELPER);
fs.chmodSync(script, 0o755);
const r = spawnSync('/bin/sh', [script, '999999', app, stage, 'run.sh'], { encoding: 'utf8', timeout: 15000 });
await new Promise((resolve) => setTimeout(resolve, 2200));
const ok = fs.existsSync(path.join(app, 'new.txt')) && !fs.existsSync(path.join(app, 'old.txt')) && fs.existsSync(marker) && fs.readFileSync(marker, 'utf8').trim() === 'new';
console.log(`helper exit=${r.status} replaced=${ok}`);
fs.rmSync(tmp, { recursive: true, force: true });
if (!ok) process.exit(1);
console.log('Update helper: replacement + relaunch OK');
