import { chromium } from 'playwright-core';
import fs from 'node:fs';
import path from 'node:path';
const OUT = 'test-results';
fs.mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || chromium.executablePath(), args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
const checks = [];
const check = (name, ok, detail = '') => { checks.push({ name, ok: !!ok, detail }); console.log(`  ${ok ? '✓' : '✗'} ${name}${detail ? ` — ${detail}` : ''}`); };
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' });
await page.waitForSelector('.app');
await page.setInputFiles('input[type=file]', path.resolve('tests/fixtures/source-av.webm'));
await page.waitForFunction(() => document.querySelectorAll('.clip').length >= 1, null, { timeout: 60000 });
await page.waitForTimeout(900);
await page.evaluate(() => {
  const s = window.__cutline.getState();
  const track = s.project.tracks.find((t) => t.kind === 'video');
  const first = track.clips[0];
  s.updateClip(first.id, { duration: 2 });
  const asset = Object.values(s.assets).find((a) => a.kind === 'video');
  s.addClipToTrack(track.id, asset, 2, 2);
  s.addClipToTrack(track.id, asset, 4, 2);
});
await page.waitForTimeout(600);
const clips = page.locator('.track-row.video .clip');
check('three adjacent clips', (await clips.count()) === 3, String(await clips.count()));

console.log('\n[1] Slide');
let boxes = [];
for (let i = 0; i < 3; i++) boxes.push(await clips.nth(i).boundingBox());
await page.keyboard.down('Shift');
await page.mouse.move(boxes[1].x + boxes[1].width / 2, boxes[1].y + boxes[1].height / 2);
await page.mouse.down();
await page.mouse.move(boxes[1].x + boxes[1].width / 2 + 20, boxes[1].y + boxes[1].height / 2, { steps: 6 });
await page.mouse.up();
await page.keyboard.up('Shift');
await page.waitForTimeout(400);
const slide = await page.evaluate(() => window.__cutline.getState().project.tracks.find((t) => t.kind === 'video').clips.map((c) => ({ start: +c.start.toFixed(3), dur: +c.duration.toFixed(3) })));
check('slide trims both neighbours and moves clip', slide[0].dur > 2.2 && slide[1].start > 2.2 && slide[2].start > 4.2 && slide[2].dur < 1.8, JSON.stringify(slide));

console.log('\n[2] Multi-select + group move + delete');
boxes = [];
for (let i = 0; i < 3; i++) boxes.push(await clips.nth(i).boundingBox());
await page.mouse.click(boxes[0].x + boxes[0].width / 2, boxes[0].y + boxes[0].height / 2);
await page.keyboard.down('Control');
await page.mouse.click(boxes[1].x + boxes[1].width / 2, boxes[1].y + boxes[1].height / 2);
await page.keyboard.up('Control');
await page.waitForTimeout(300);
const selected = await page.evaluate(() => window.__cutline.getState().selectedClips);
check('Ctrl-click selects two clips', selected.length === 2, JSON.stringify(selected));
check('both clips show selection', (await page.locator('.clip.selected').count()) === 3 || (await page.locator('.clip.selected').count()) === 2, String(await page.locator('.clip.selected').count()));
const beforeGroup = await page.evaluate(() => window.__cutline.getState().project.tracks.find((t) => t.kind === 'video').clips.map((c) => c.start));
await page.mouse.move(boxes[1].x + boxes[1].width / 2, boxes[1].y + boxes[1].height / 2);
await page.mouse.down();
await page.mouse.move(boxes[1].x + boxes[1].width / 2 + 30, boxes[1].y + boxes[1].height / 2, { steps: 6 });
await page.mouse.up();
await page.waitForTimeout(400);
const afterGroup = await page.evaluate(() => window.__cutline.getState().project.tracks.find((t) => t.kind === 'video').clips.map((c) => c.start));
check('group drag shifts both selected clips', afterGroup[0] > beforeGroup[0] + 0.2 && afterGroup[1] > beforeGroup[1] + 0.2 && Math.abs((afterGroup[0] - beforeGroup[0]) - (afterGroup[1] - beforeGroup[1])) < 0.02, JSON.stringify({ beforeGroup, afterGroup }));
await page.keyboard.press('Delete');
await page.waitForTimeout(400);
check('Delete removes the group', (await clips.count()) === 1, String(await clips.count()));
await page.screenshot({ path: `${OUT}/desktop-multiselect.png` });
check('no runtime errors', errors.length === 0, errors.slice(0, 2).join(' | '));
fs.writeFileSync(`${OUT}/multi-report.json`, JSON.stringify({ checks, errors, slide }, null, 2));
await browser.close();
process.exit(checks.every((c) => c.ok) ? 0 : 1);
