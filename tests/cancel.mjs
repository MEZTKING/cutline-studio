import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || chromium.executablePath(), args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 860 }, acceptDownloads: true });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(process.env.APP_URL || 'http://127.0.0.1:5173/', { waitUntil: 'networkidle' });
await page.waitForSelector('.app');
await page.evaluate(() => window.__cutline.getState().addText());
await page.waitForTimeout(400);
await page.locator('.topbar .btn.primary').click();
await page.waitForSelector('.modal');
await page.waitForTimeout(500);
const startBtn = page.locator('.modal-foot .btn.primary');
await startBtn.click();
await page.waitForTimeout(350);
const running = await page.locator('.progress').count();
await page.locator('.modal-foot .btn.danger').click();
await page.waitForTimeout(600);
const idle = await page.locator('.modal-foot .btn.primary').isEnabled();
const dlPromise = page.waitForEvent('download', { timeout: 120000 });
await page.locator('.modal-foot .btn.primary').click();
const dl = await dlPromise;
const gone = !!dl;
console.log(JSON.stringify({ runningProgressShown: running === 1, retryEnabled: idle, secondExportDownloaded: gone, errors }));
await browser.close();
process.exit(running === 1 && idle && gone && errors.length === 0 ? 0 : 1);
